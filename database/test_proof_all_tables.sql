-- 18. พิสูจน์ STORE_SETTINGS (การตั้งค่าร้านค้า)
-- การทดสอบบนเว็บ: หน้าแอดมินกดสวิตช์ "เปิดร้าน/ปิดร้าน" หรือแก้ไขเบอร์พร้อมเพย์
-- สิ่งที่สังเกต: ฟิลด์ is_open เปลี่ยนเป็น 1 (เปิด) หรือ 0 (ปิด) ทันที
SELECT store_name, promptpay_number, is_open, open_time, close_time, vat_rate 
FROM STORE_SETTINGS;
