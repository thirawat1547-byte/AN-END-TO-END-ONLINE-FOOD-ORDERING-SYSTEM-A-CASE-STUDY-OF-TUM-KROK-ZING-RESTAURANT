-- ====================================================================
-- รวมคำสั่ง SQL สำหรับ "พิสูจน์การเชื่อมต่อฐานข้อมูลจริง" ทุกตาราง
-- วิชา Advanced Database: ระบบสั่งอาหารออนไลน์ร้านตำครกซิ่ง
-- ====================================================================

USE tum_krok_zing;

-- --------------------------------------------------------------------
-- 1. พิสูจน์ตาราง USERS (ผู้ใช้งานและสมาชิก)
-- การทดสอบบนเว็บ: กดปุ่ม "สมัครสมาชิก" (Register) หรือ "แก้ไขโปรไฟล์"
-- สิ่งที่สังเกต: รายชื่อผู้ใช้ล่าสุด, รหัสผ่านถูกเข้ารหัส bcrypt, และ Role
-- --------------------------------------------------------------------
SELECT user_id, username, email, phone_number, role 
FROM USERS 
ORDER BY user_id DESC LIMIT 5;


-- --------------------------------------------------------------------
-- 2. พิสูจน์ตาราง CATEGORIES (หมวดหมู่อาหาร)
-- การทดสอบบนเว็บ: ดูแถบหมวดหมู่ในหน้าเมนู (อีสาน, ต้ม/แกง, ทอด/ย่าง, ยำ, เครื่องดื่ม)
-- สิ่งที่สังเกต: ชื่อหมวดหมู่ตรงกับแท็บบนหน้าสั่งอาหารเป๊ะๆ
-- --------------------------------------------------------------------
SELECT category_id, category_name 
FROM CATEGORIES;


-- --------------------------------------------------------------------
-- 3. พิสูจน์ตาราง MENUS (เมนูอาหารและสถานะการขาย)
-- การทดสอบบนเว็บ: แอดมินกด "เพิ่มเมนู" หรือสวิตช์ "เปิด/ปิดขายเมนู"
-- สิ่งที่สังเกต: ราคา แคลอรี่ และฟิลด์ is_available เปลี่ยนตามสวิตช์
-- --------------------------------------------------------------------
SELECT menu_id, menu_name, price, calories, is_available, image_url 
FROM MENUS 
ORDER BY menu_id DESC LIMIT 5;


-- --------------------------------------------------------------------
-- 4. พิสูจน์ตาราง INGREDIENTS (คลังวัตถุดิบและสต็อก)
-- การทดสอบบนเว็บ: แอดมินกด "เติมสต็อก" หรือเมื่อมีลูกค้าสั่งอาหาร (สต็อกจะลด)
-- สิ่งที่สังเกต: ค่า quantity_in_stock ลดลงอัตโนมัติเมื่อสั่งอาหาร
-- --------------------------------------------------------------------
SELECT ingredient_id, ingredient_name, quantity_in_stock, unit, reorder_level 
FROM INGREDIENTS 
ORDER BY ingredient_id ASC LIMIT 10;


-- --------------------------------------------------------------------
-- 5. พิสูจน์ตาราง MENU_INGREDIENTS (สูตรอาหารตัดสต็อก - Junction Table)
-- การทดสอบบนเว็บ: หน้าแอดมินคลิก "สูตรอาหาร" (Recipe) ของแต่ละเมนู
-- สิ่งที่สังเกต: แสดงว่าเมนูนี้ (เช่น ส้มตำไทย) ผูกกับวัตถุดิบอะไรกี่กรัม/หน่วย
-- --------------------------------------------------------------------
SELECT m.menu_name AS 'ชื่อเมนู', i.ingredient_name AS 'วัตถุดิบที่ใช้', mi.quantity_used AS 'ปริมาณต่อจาน', i.unit AS 'หน่วย'
FROM MENU_INGREDIENTS mi
JOIN MENUS m ON mi.menu_id = m.menu_id
JOIN INGREDIENTS i ON mi.ingredient_id = i.ingredient_id
WHERE m.menu_id = 1; -- ดูสูตรส้มตำไทย


-- --------------------------------------------------------------------
-- 6. พิสูจน์ตาราง ALLERGENS (ข้อมูลสารก่อภูมิแพ้)
-- การทดสอบบนเว็บ: ป้ายเตือนสารก่อภูมิแพ้บนการ์ดเมนู
-- สิ่งที่สังเกต: มีรายการ กุ้ง/อาหารทะเล, ถั่วลิสง
-- --------------------------------------------------------------------
SELECT allergen_id, allergen_name, icon_url 
FROM ALLERGENS;


-- --------------------------------------------------------------------
-- 7. พิสูจน์ตาราง MENU_ALLERGENS (ความสัมพันธ์เมนูกับสารก่อภูมิแพ้ - Junction Table)
-- การทดสอบบนเว็บ: หน้าแอดมินติ๊กเลือกสารก่อภูมิแพ้ให้เมนู
-- สิ่งที่สังเกต: เชื่อมโยงเมนูกับสารก่อภูมิแพ้ที่ถูกต้อง
-- --------------------------------------------------------------------
SELECT m.menu_name AS 'ชื่อเมนู', a.allergen_name AS 'สารก่อภูมิแพ้ที่มี'
FROM MENU_ALLERGENS ma
JOIN MENUS m ON ma.menu_id = m.menu_id
JOIN ALLERGENS a ON ma.allergen_id = a.allergen_id;


-- --------------------------------------------------------------------
-- 8. พิสูจน์ตาราง TABLES (สถานะโต๊ะอาหาร)
-- การทดสอบบนเว็บ: ลูกค้านั่งโต๊ะ หรือพนักงานกด "เปิดโต๊ะ/เคลียร์โต๊ะ"
-- สิ่งที่สังเกต: ค่า status เปลี่ยนสลับระหว่าง 'AVAILABLE' กับ 'OCCUPIED'
-- --------------------------------------------------------------------
SELECT table_id, table_number, capacity, status 
FROM TABLES;


-- --------------------------------------------------------------------
-- 9. พิสูจน์ตาราง ORDERS (คำสั่งซื้อหลัก)
-- การทดสอบบนเว็บ: ลูกค้ากดปุ่ม "กดยืนยันสั่งอาหาร" หรือครัวกด "รับออเดอร์"
-- สิ่งที่สังเกต: มีแถวออเดอร์ใหม่พร้อมยอดเงินรวม และ status เปลี่ยนเป็น PREPARING/SERVED
-- --------------------------------------------------------------------
SELECT order_id, table_id, order_type, total_price, status, created_at 
FROM ORDERS 
ORDER BY order_id DESC LIMIT 5;


-- --------------------------------------------------------------------
-- 10. พิสูจน์ตาราง ORDER_ITEMS (รายการอาหารย่อยในบิล)
-- การทดสอบบนเว็บ: รายการที่ลูกค้าสั่งลงในตะกร้า พร้อมโน้ตพิเศษ (เช่น เผ็ดน้อย)
-- สิ่งที่สังเกต: จำนวนจาน ราคาต่อหน่วย และข้อความหมายเหตุ (notes)
-- --------------------------------------------------------------------
SELECT oi.order_item_id, oi.order_id, m.menu_name, oi.quantity, oi.unit_price, oi.notes 
FROM ORDER_ITEMS oi
JOIN MENUS m ON oi.menu_id = m.menu_id
ORDER BY oi.order_item_id DESC LIMIT 5;


-- --------------------------------------------------------------------
-- 11. พิสูจน์ตาราง TRANSACTIONS (การชำระเงินและสลิป)
-- การทดสอบบนเว็บ: ลูกค้าหรือพนักงานกด "แจ้งชำระเงิน / แนบสลิปโอน"
-- สิ่งที่สังเกต: บันทึกยอดเงิน ช่องทางชำระ และลิงก์รูปสลิป
-- --------------------------------------------------------------------
SELECT transaction_id, order_id, amount, payment_method, payment_status, payment_slip_url 
FROM TRANSACTIONS 
ORDER BY transaction_id DESC LIMIT 5;


-- --------------------------------------------------------------------
-- 12. พิสูจน์ตาราง PROMOTIONS (โค้ดส่วนลด)
-- การทดสอบบนเว็บ: หน้าแอดมินสร้างโค้ด หรือหน้าสั่งอาหารกรอกโค้ดส่วนลด
-- สิ่งที่สังเกต: รหัสโค้ด มูลค่าลด และยอดสั่งซื้อขั้นต่ำ
-- --------------------------------------------------------------------
SELECT promo_id, code, discount_type, discount_value, min_order_price, expiry_date 
FROM PROMOTIONS;


-- ====================================================================
-- 5 DATABASE VIEWS (พิสูจน์มุมมองข้อมูลระดับสูง)
-- ====================================================================

-- 13. พิสูจน์ ORDER_SUMMARIES_VIEW (สรุปยอดขายรายบิล)
-- การทดสอบบนเว็บ: หน้าประวัติออเดอร์ หรือรายงานยอดขายของแอดมิน
-- สิ่งที่สังเกต: ดึงเลขโต๊ะมา JOIN อัตโนมัติโดยไม่ต้องเขียนคำสั่ง JOIN เอง
SELECT * FROM ORDER_SUMMARIES_VIEW 
ORDER BY order_id DESC LIMIT 5;


-- 14. พิสูจน์ TRANSACTION_RECEIPTS_VIEW (สรุปใบเสร็จรับเงิน)
-- การทดสอบบนเว็บ: หน้าประวัติการชำระเงิน และใบเสร็จรับเงิน
-- สิ่งที่สังเกต: ดึงชื่อลูกค้าและยอดจ่ายจาก 3 ตารางมารวมเป็นใบเสร็จเดียว
SELECT * FROM TRANSACTION_RECEIPTS_VIEW 
ORDER BY transaction_id DESC LIMIT 5;


-- 15. พิสูจน์ TOP_SELLING_MENUS_VIEW (เมนูขายดี)
-- การทดสอบบนเว็บ: แดชบอร์ดสรุป 5 อันดับเมนูขายดี
-- สิ่งที่สังเกต: คำนวณ SUM ยอดขาย และจัดอันดับเมนูให้อัตโนมัติ
SELECT * FROM TOP_SELLING_MENUS_VIEW 
ORDER BY total_sold DESC LIMIT 5;


-- 16. พิสูจน์ LOW_STOCK_ALERTS_VIEW (แจ้งเตือนของใกล้หมด)
-- การทดสอบบนเว็บ: กล่องเตือนสีแดงในหน้าคลังวัตถุดิบของแอดมิน
-- สิ่งที่สังเกต: แสดงเฉพาะรายการที่ quantity_in_stock <= reorder_level
SELECT * FROM LOW_STOCK_ALERTS_VIEW;


-- 17. พิสูจน์ LIVE_TABLE_STATUS_VIEW (สถานะโต๊ะสดเรียลไทม์)
-- การทดสอบบนเว็บ: ผังโต๊ะของพนักงานเสิร์ฟและแคชเชียร์
-- สิ่งที่สังเกต: แสดงเลขโต๊ะ สถานะ และยอดค้างจ่ายปัจจุบัน
SELECT * FROM LIVE_TABLE_STATUS_VIEW;


